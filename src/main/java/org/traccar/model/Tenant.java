package org.traccar.model;

import org.traccar.storage.StorageName;

@StorageName("tc_tenants")
public class Tenant extends ExtendedModel {

    private String name;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    private String legalName;

    public String getLegalName() {
        return legalName;
    }

    public void setLegalName(String legalName) {
        this.legalName = legalName;
    }

    private String document;

    public String getDocument() {
        return document;
    }

    public void setDocument(String document) {
        this.document = document;
    }

    private String email;

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    private String phone;

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    private String contactName;

    public String getContactName() {
        return contactName;
    }

    public void setContactName(String contactName) {
        this.contactName = contactName;
    }

    private String zipCode;

    public String getZipCode() {
        return zipCode;
    }

    public void setZipCode(String zipCode) {
        this.zipCode = zipCode;
    }

    private String street;

    public String getStreet() {
        return street;
    }

    public void setStreet(String street) {
        this.street = street;
    }

    private String streetNumber;

    public String getStreetNumber() {
        return streetNumber;
    }

    public void setStreetNumber(String streetNumber) {
        this.streetNumber = streetNumber;
    }

    private String complement;

    public String getComplement() {
        return complement;
    }

    public void setComplement(String complement) {
        this.complement = complement;
    }

    private String district;

    public String getDistrict() {
        return district;
    }

    public void setDistrict(String district) {
        this.district = district;
    }

    private String city;

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }

    private String state;

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }

    private Double baseLatitude;

    public Double getBaseLatitude() {
        return baseLatitude;
    }

    public void setBaseLatitude(Double baseLatitude) {
        this.baseLatitude = baseLatitude;
    }

    private Double baseLongitude;

    public Double getBaseLongitude() {
        return baseLongitude;
    }

    public void setBaseLongitude(Double baseLongitude) {
        this.baseLongitude = baseLongitude;
    }

    private Integer baseRadius;

    public Integer getBaseRadius() {
        return baseRadius;
    }

    public void setBaseRadius(Integer baseRadius) {
        this.baseRadius = baseRadius;
    }

    private boolean disabled;

    public boolean getDisabled() {
        return disabled;
    }

    public void setDisabled(boolean disabled) {
        this.disabled = disabled;
        this.disabledSpecified = true;
    }

    private boolean disabledSpecified;

    public boolean disabledSpecified() {
        return disabledSpecified;
    }

}
